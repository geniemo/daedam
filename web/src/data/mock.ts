/** §10 재생 바 파형 — 결정적(deterministic) 높이. 서버가 실제 파형을 주면 교체. */
export function waveformBars(seed: number, count = 34): number[] {
  return Array.from({ length: count }, (_, i) => {
    const v = (Math.sin(seed * 2.3 + i * 0.9) + Math.sin(seed + i * 2.1)) / 2
    return Math.round(24 + ((v + 1) / 2) * 74) // 24~98%
  })
}

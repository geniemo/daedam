export const ctxFor = (company: string): CompanyContext =>
  ctxByCompany[company] ?? {
    product: '최근 공개한 서비스',
    news: '최근 1년 보도자료와 채용 페이지에서 반복되는 사업 방향을 확인했습니다.',
  }

/** {C} 회사명 · {P} 제품명 · {N} 뉴스 문장 · {R} 직무명 치환 */
export function fill(str: string, company: string, role = ''): string {
  const ctx = ctxFor(company)
  return str
    .split('{C}')
    .join(company)
    .split('{P}')
    .join(ctx.product)
    .split('{N}')
    .join(ctx.news)
    .split('{R}')
    .join(role.split(' · ')[0])
}

